/**
 * Get filtered brand list based on vehicle segment (car | bike | scooter)
 */
export function getBrandsForSegment(segment) {
  if (segment === 'bike') return VEHICLE_BRANDS.bike;
  if (segment === 'scooter') return VEHICLE_BRANDS.scooter;
  if (segment && segment !== 'car') return VEHICLE_BRANDS.car;
  // If no segment or car, merge all or return car
  return VEHICLE_BRANDS.car;
}

/**
 * Get models for selected brand
 */
export function getModelsForBrand(brand) {
  if (!brand) return [];
  const normalized = Object.keys(BRAND_MODELS).find(
    k => k.toLowerCase() === brand.trim().toLowerCase() || brand.trim().toLowerCase().includes(k.toLowerCase())
  );
  return normalized ? BRAND_MODELS[normalized] : [];
}
